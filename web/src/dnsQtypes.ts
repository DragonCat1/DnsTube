/** 列表中优先展示的常用查询类型（须为 MIEKG_TYPE_TO_STRING 子集） */
const PRIORITY: string[] = [
  'A',
  'AAAA',
  'CNAME',
  'MX',
  'NS',
  'PTR',
  'SOA',
  'SRV',
  'TXT',
  'ANY',
  'CAA',
  'HTTPS',
  'SVCB',
  'TLSA',
  'DS',
  'DNSKEY',
  'RRSIG',
  'NSEC',
  'NSEC3',
  'OPT',
]

const allSet = new Set(MIEKG_TYPE_TO_STRING)
const prioritySet = new Set(PRIORITY)

const orderedValues = [
  ...PRIORITY.filter((t) => allSet.has(t)),
  ...MIEKG_TYPE_TO_STRING.filter((t) => !prioritySet.has(t)).sort((a, b) =>
    a.localeCompare(b, 'en'),
  ),
]

/** ant-design-vue Select 的 options（label 与 value 一致，便于搜索） */
export const dnsQtypeSelectOptions = orderedValues.map((value) => ({
  value,
  label: value,
}))
